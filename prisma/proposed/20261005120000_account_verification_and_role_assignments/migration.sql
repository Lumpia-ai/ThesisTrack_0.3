-- ---------------------------------------------------------------------------------------------
-- 5. Backfill: one active assignment per existing user, matching the role they hold today.
--    - Institution-level roles -> scope 'INSTITUTION' (these roles are not department-limited today).
--    - Department-scoped roles -> the mapped Department.id, using ONLY the approved exact mappings
--      (matched case-insensitively after trimming; no partial or fuzzy matching).
--    - Department-scoped roles whose department is empty or unmapped -> scope 'NONE', departmentId
--      NULL. 'NONE' grants no department-wide access (never broader than today); the account stays
--      active for its own records and is listed in the backfill report for an administrator to fix.
--    Idempotent: re-running inserts nothing new.
-- ---------------------------------------------------------------------------------------------
WITH
-- BEGIN department_map (scripts/test-db.mjs reuses this block for the read-only preview)
department_map ("raw", "departmentId") AS (
    VALUES
        ('BSIT', 'IT'), ('BSMET', 'MET'), ('BSTCM', 'TCM'), ('BSESM', 'ESM'), ('BSNAME', 'NAME'),
        ('IT', 'IT'), ('MET', 'MET'), ('TCM', 'TCM'), ('ESM', 'ESM'), ('NAME', 'NAME'),
        -- Approved 2026-10-05: legacy labels used by existing staff accounts.
        ('ICT', 'IT'), ('TCM OFFICE', 'TCM')
),
-- END department_map
backfill AS (
    SELECT
        u."id" AS "userId",
        u."role",
        CASE
            WHEN u."role" IN ('system_admin', 'research_head', 'admin', 'library', 'tech_transfer') THEN NULL
            ELSE d."id"
        END AS "departmentId",
        CASE
            WHEN u."role" IN ('system_admin', 'research_head', 'admin', 'library', 'tech_transfer') THEN 'INSTITUTION'
            WHEN d."id" IS NOT NULL THEN d."id"
            ELSE 'NONE'
        END AS "scope"
    FROM "User" u
    LEFT JOIN department_map m ON m."raw" = upper(btrim(u."department"))
    LEFT JOIN "Department" d ON d."id" = m."departmentId"
),
inserted AS (
    INSERT INTO "UserRoleAssignment" ("id", "userId", "role", "scope", "departmentId", "status", "grantedById", "grantedAt", "createdAt", "updatedAt")
    SELECT gen_random_uuid()::text, b."userId", b."role", b."scope", b."departmentId", 'active', NULL, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
    FROM backfill b
    ON CONFLICT ("userId", "role", "scope") DO NOTHING
    RETURNING "scope"
)
-- One audit entry records that the migration (not a person) granted these roles.
INSERT INTO "AuditLog" ("id", "actorId", "action", "entityType", "entityId", "metadata", "createdAt")
SELECT
    gen_random_uuid()::text,
    NULL,
    'role_assignment.backfilled',
    'UserRoleAssignment',
    'migration:20261005120000_account_verification_and_role_assignments',
    jsonb_build_object(
        'total', count(*),
        'institution', count(*) FILTER (WHERE "scope" = 'INSTITUTION'),
        'department', count(*) FILTER (WHERE "scope" NOT IN ('INSTITUTION', 'NONE')),
        'noDepartment', count(*) FILTER (WHERE "scope" = 'NONE')
    ),
    CURRENT_TIMESTAMP
FROM inserted
HAVING count(*) > 0;
